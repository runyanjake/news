const entry = (tagline, url = 'https://example.com/a') => ({
  topic: tagline,
  tagline,
  summary: `${tagline} summary`,
  score: 1,
  ai_generated: true,
  sources: [{ name: 'Example', title: `${tagline} title`, url, score: 1 }],
});
const report = (date, entries = [entry('Lead story'), entry('Second story')]) => ({
  date,
  site_name: 'PWS NEWS',
  title: `PWS NEWS — ${date}`,
  generated_at: `${date}T15:00:00Z`,
  entries,
});

describe('report format', () => {
  it('renders the lead and remaining entries', () => {
    const html = renderReport(report('2026-10-22'));
    assert.match(html, /class="lead"[\s\S]*Lead story/);
    assert.match(html, /class="columns"[\s\S]*Second story/);
  });

  it('keeps the top story as lead and mixes the rest the same way on every render', () => {
    const entries = ['Lead story', ...Array.from({ length: 12 }, (_, i) => `Story ${i}`)].map((t) => entry(t));
    const order = (html) => [...html.matchAll(/class="tagline"[^>]*>([^<]+)</g)].map((m) => m[1]);
    const rendered = order(renderReport(report('2026-10-22', entries)));

    assert.equal(rendered[0], 'Lead story');
    assert.deepEqual([...rendered].sort(), entries.map((e) => e.tagline).sort());
    assert.deepEqual(order(renderReport(report('2026-10-22', entries))), rendered);
    const regenerated = { ...report('2026-10-22', entries), generated_at: '2026-10-22T23:30:00Z' };
    assert.notDeepEqual(order(renderReport(regenerated)), rendered);
  });

  it('centers the lead source list as a left-aligned block', () => {
    const html = renderReport(report('2026-10-22'));
    assert.match(html, /class="lead"[\s\S]*<ul class="sources">/);
    assert.match(html, /\.lead \.sources \{[^}]*display: inline-block;[^}]*text-align: left;/);
  });

  it('escapes feed content and rejects non-http links', () => {
    const html = renderReport(report('2026-10-22', [entry('<script>x</script>', 'javascript:alert(1)')]));
    assert.ok(!html.includes('<script>x'));
    assert.ok(html.includes('&lt;script&gt;'));
    assert.ok(!html.includes('javascript:'));
  });

  it('handles an empty report', () => {
    assert.match(renderReport(report('2026-10-22', [])), /No stories/);
  });

  it('takes the site name and page title from the backend report', () => {
    const html = renderReport({ ...report('2026-10-22'), site_name: 'Daily <B>', title: 'Daily <B> — Tuesday' });
    assert.match(html, /<title>Daily &lt;B&gt; — Tuesday<\/title>/);
    assert.match(html, /<h1><a href="\/">Daily &lt;B&gt;<\/a><\/h1>/);
  });

  it('links the privacy policy from every page', () => {
    assert.match(renderReport(report('2026-10-22')), /href="\/privacy\/"/);
  });

  it('privacy page has a dated policy, a disclaimer and the source list', () => {
    const html = renderPrivacy('PWS NEWS', [{ name: 'Zeta <Z>' }, { name: 'Alpha' }, { name: 'Alpha' }]);
    assert.match(html, /Last updated: <time datetime="\d{4}-\d{2}-\d{2}">/);
    assert.match(html, /<h3>Privacy Policy<\/h3>[\s\S]*standard server logging[\s\S]*not sold to advertisers/);
    assert.match(html, /<h3>Disclaimer<\/h3>[\s\S]*generated by AI[\s\S]*original authors[\s\S]*not\s+reflect the views of PWS NEWS/);
    assert.match(html, /<ul class="source-list"><li>Alpha<\/li><li>Zeta &lt;Z&gt;<\/li><\/ul>/);
  });

  it('uses only self-hosted OFL fonts with generic fallbacks', () => {
    const html = renderReport(report('2026-10-22'));
    assert.match(html, /url\('\/assets\/source-serif-4\.woff2'\)/);
    assert.match(html, /url\('\/assets\/source-sans-3\.woff2'\)/);
    assert.doesNotMatch(html, /Georgia|Times|Courier|Arial|Helvetica/);
  });

  it('offers small font and theme toggles on every page', () => {
    for (const html of [renderReport(report('2026-10-22')), renderPrivacy('PWS NEWS')]) {
      assert.match(html, /<div class="prefs"[\s\S]*data-pref="font"[\s\S]*data-pref="theme"/);
      assert.ok(html.indexOf('localStorage') < html.indexOf('</head>')); // applied before first paint
    }
  });
});

describe('publishReport', () => {
  let dir;
  beforeEach(async () => { dir = await mkdtemp(path.join(tmpdir(), 'site-')); });
  afterEach(() => rm(dir, { recursive: true, force: true }));

  it('keeps history and points the front page at the newest report', async () => {
    await publishReport(dir, report('2026-10-22', [entry('Newer')]));
    await publishReport(dir, report('2026-10-21', [entry('Older')]));

    assert.match(await readFile(path.join(dir, 'index.html'), 'utf8'), /Newer/);
    assert.match(await readFile(path.join(dir, 'reports/2026-10-21/index.html'), 'utf8'), /Older/);
    const archive = await readFile(path.join(dir, 'archive/index.html'), 'utf8');
    assert.ok(archive.indexOf('2026-10-22') < archive.indexOf('2026-10-21'));
  });

  it('publishSite writes the privacy page and font assets', async () => {
    await publishSite(dir, 'PWS NEWS', [{ name: 'BBC World' }]);
    assert.match(await readFile(path.join(dir, 'privacy/index.html'), 'utf8'), /Privacy Policy[\s\S]*BBC World/);
    for (const f of ['source-serif-4.woff2', 'source-sans-3.woff2', 'OFL-source-serif-4.txt', 'OFL-source-sans-3.txt']) {
      await readFile(path.join(dir, 'assets', f));
    }
  });

  it('keeps every generation and shows only the newest by timestamp', async () => {
    const at = (time, tagline) => ({ ...report('2026-10-22', [entry(tagline)]), generated_at: `2026-10-22T${time}Z` });
    const front = () => readFile(path.join(dir, 'index.html'), 'utf8');
    await publishReport(dir, at('15:00:00', 'Morning'));
    await publishReport(dir, at('23:30:00', 'Evening'));
    await publishReport(dir, at('09:00:00', 'Early re-render')); // older generation must not take over

    assert.match(await front(), /Evening/);
    assert.match(await readFile(path.join(dir, 'reports/2026-10-22/index.html'), 'utf8'), /Evening/);
    for (const [stamp, tagline] of [['20261022T150000Z', 'Morning'], ['20261022T090000Z', 'Early re-render']]) {
      assert.match(await readFile(path.join(dir, `archive/2026-10-22/${stamp}/index.html`), 'utf8'), new RegExp(tagline));
    }
    const archive = await readFile(path.join(dir, 'archive/index.html'), 'utf8');
    assert.ok(archive.indexOf('20261022T233000Z') < archive.indexOf('20261022T150000Z'));

    await publishReport(dir, report('2026-10-21', [entry('Yesterday')]));
    assert.match(await front(), /Evening/);
  });

  it('rejects unsafe dates', async () => {
    await assert.rejects(publishReport(dir, report('../../etc')), /Invalid report date/);
  });

  it('rebuildAll re-renders every stored report', async () => {
    const stored = { '2026-10-21': report('2026-10-21'), '2026-10-22': report('2026-10-22') };
    const evening = { ...report('2026-10-22', [entry('Evening')]), generated_at: '2026-10-22T23:00:00Z' };
    const generations = { '2026-10-22': { '20261022T230000Z': evening, '20261022T150000Z': stored['2026-10-22'] } };
    const backend = {
      listDates: async () => Object.keys(stored).reverse(),
      getReport: async (d) => stored[d],
      listGenerations: async (d) => Object.keys(generations[d] ?? {}),
      getGeneration: async (d, s) => generations[d][s],
      listSources: async () => [{ name: 'Example' }],
    };
    assert.equal(await rebuildAll(backend, dir), 2);
    assert.match(await readFile(path.join(dir, 'privacy/index.html'), 'utf8'), /<li>Example<\/li>/);
    await readFile(path.join(dir, 'archive/2026-10-22/20261022T150000Z/index.html'));
    assert.match(await readFile(path.join(dir, 'index.html'), 'utf8'), /Evening/);
    await readFile(path.join(dir, 'reports/2026-10-21/index.html'));
    assert.match(await readFile(path.join(dir, 'index.html'), 'utf8'), /2026-10-22/);
  });

  it('publishLatestIfNew renders a regenerated report once', async () => {
    let latest = report('2026-10-22', [entry('First run')]);
    const backend = { getReport: async (d) => (d === 'latest' ? latest : null), listSources: async () => [] };
    const front = () => readFile(path.join(dir, 'index.html'), 'utf8');

    let renderedAt = await publishLatestIfNew(backend, dir, null);
    assert.match(await front(), /First run/);

    latest = { ...report('2026-10-22', [entry('Second run')]), generated_at: '2026-10-22T18:00:00Z' };
    renderedAt = await publishLatestIfNew(backend, dir, renderedAt);
    assert.equal(renderedAt, '2026-10-22T18:00:00Z');
    assert.match(await front(), /Second run/);

    await rm(path.join(dir, 'index.html'));
    assert.equal(await publishLatestIfNew(backend, dir, renderedAt), renderedAt);
    await assert.rejects(front()); // unchanged report is not re-rendered
  });
});

describe('backend client', () => {
  const json = (body, status = 200) => new Response(JSON.stringify(body), { status });

  it('starts generation, polls the job, then fetches the report', async () => {
    const calls = [];
    const statuses = [{ running: true }, { running: false, last_date: '2026-10-22', last_error: null }];
    const fetchImpl = async (url, init = {}) => {
      calls.push(`${init.method ?? 'GET'} ${new URL(url).pathname}`);
      if (url.endsWith('/generate') && init.method === 'POST') {
        assert.equal(init.headers['X-Admin-Token'], 'tok');
        return json({ running: true }, 202);
      }
      if (url.endsWith('/api/jobs/generate')) return json(statuses.shift());
      return json(report('2026-10-22'));
    };
    const backend = createBackend({ baseUrl: 'http://b', adminToken: 'tok', fetchImpl, pollMs: 1 });

    assert.equal((await backend.generate()).date, '2026-10-22');
    assert.deepEqual(calls, [
      'POST /api/reports/generate', 'GET /api/jobs/generate', 'GET /api/jobs/generate', 'GET /api/reports/2026-10-22',
    ]);
  });

  it('surfaces job failures', async () => {
    const fetchImpl = async (url, init = {}) =>
      init.method === 'POST' ? json({}, 202) : json({ running: false, last_error: 'feeds down' });
    const backend = createBackend({ baseUrl: 'http://b', adminToken: 'tok', fetchImpl, pollMs: 1 });
    await assert.rejects(backend.generate(), /feeds down/);
  });
});

describe('msUntilNext', () => {
  it('targets later today or tomorrow', () => {
    const now = new Date(2026, 9, 22, 7, 30);
    assert.equal(msUntilNext(now, '08:00'), 30 * 60_000);
    assert.equal(msUntilNext(new Date(2026, 9, 22, 8, 0), '08:00'), 24 * 3600_000);
  });

  it('rejects malformed times', () => {
    assert.throws(() => msUntilNext(new Date(), '8am'), /Invalid time/);
  });
});
